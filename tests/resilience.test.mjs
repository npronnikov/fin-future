test('TS-097: failed durable write changes neither live state nor success events, retry works', async (t) => {
    const h = await harness(t);
    await h.setup();
    let emitted = 0;
    const listener = () => emitted++;
    h.app.store.listeners.add(listener);
    const before = JSON.stringify(h.app.store.state);
    const seq = h.app.store.state.sequence;
    await h.api('maxim', '/demo/fault', { kind: 'storage' });
    await rejectsCode(() => h.cmd('ivan', 'task.create', { projectId: h.project.id, title: 'Не должно сохраниться' }), 'StorageUnavailable');
    assert.equal(JSON.stringify(h.app.store.state), before);
    assert.equal(h.app.store.state.sequence, seq);
    assert.equal(emitted, 0);
    const task = await h.cmd('ivan', 'task.create', { projectId: h.project.id, title: 'Успешный повтор' });
    assert.ok(task.id);
    assert.ok(emitted > 0);
});
test('TS-098: corrupt primary enters read-only verified-backup recovery, preserves corrupt bytes, never silently resets', async (t) => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'kontur-corrupt-'));
    t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
    let store = new JsonStore(dir);
    store.transact(s => s.seed = 77);
    store.transact(s => s.seed = 88);
    store.close();
    fs.writeFileSync(path.join(dir, 'state.json'), 'broken snapshot');
    store = new JsonStore(dir);
    assert.ok(store.recovery);
    assert.equal(store.state.seed, 77);
    assert.throws(() => store.transact(s => s.seed = 1), e => e.code === 'StorageUnavailable');
    const r = store.recover();
    assert.equal(r.recovered, true);
    assert.equal(fs.readFileSync(path.join(dir, r.preserved), 'utf8'), 'broken snapshot');
    store.close();
    store = new JsonStore(dir);
    assert.equal(store.recovery, null);
    assert.equal(store.state.seed, 77);
    store.close();
    fs.unlinkSync(path.join(dir, 'state.backup.json'));
    fs.writeFileSync(path.join(dir, 'state.json'), '{broken');
    assert.throws(() => new JsonStore(dir), /RECOVERY_REQUIRED/);
    assert.equal(fs.readFileSync(path.join(dir, 'state.json'), 'utf8'), '{broken');
});
