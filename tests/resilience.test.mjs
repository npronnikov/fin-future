test('TS-090: actual HTTP SSE cursor replay, scoped events and invalidated session (not browser transport)', async (t) => {
    const h = await harness(t);
    await h.setup();
    const cursor = (await h.boot()).sequence;
    const channel = (await h.all('channels')).find(c => c.projectId === h.project.id);
    await h.cmd('ivan', 'message.send', { channelId: channel.id, text: 'SSE marker one' });
    await h.cmd('anna', 'message.send', { private: true, text: 'Private SSE marker' });
    const expected = h.app.store.state.events.filter(e => e.spaceId === h.spaceId && e.sequence > cursor && !e.privateTo);
    assert.ok(expected.length);
    const ac = new AbortController();
    const res = await fetch(h.url + '/api/v1/events?spaceId=' + h.spaceId + '&after=' + cursor, { headers: { Authorization: 'Bearer ' + h.tokens.ivan }, signal: ac.signal });
    assert.equal(res.status, 200);
    assert.match(res.headers.get('content-type'), /text\/event-stream/);
    const reader = res.body.getReader();
    let buffer = '';
    const stop = Date.now() + 3000;
    while (Date.now() < stop && !buffer.includes('"sequence":' + expected.at(-1).sequence)) {
        const result = await Promise.race([reader.read(), timeout(1500).then(() => ({ done: true }))]);
        if (result.done)
            break;
        buffer += new TextDecoder().decode(result.value);
    }
    ac.abort();
    const events = buffer.split('\n').filter(l => l.startsWith('data: ')).map(l => JSON.parse(l.slice(6)));
    assert.deepEqual(events.map(e => e.eventId), expected.map(e => e.eventId));
    assert.equal(new Set(events.map(e => e.eventId)).size, events.length);
    assert.ok(events.every(e => !e.privateTo));
    const last = events.at(-1).sequence;
    const polled = await h.api('ivan', '/events/poll?spaceId=' + h.spaceId + '&after=' + last);
    assert.equal(polled.items.length, 0);
    const forbidden = await h.raw('ivan', '/events/poll?spaceId=does-not-exist&after=0');
    assert.equal(forbidden.status, 403);
    const oldToken = h.tokens.ivan;
    await fetch(h.url + '/api/v1/demo/session', { method: 'POST', headers: { 'Content-Type': 'application/json', Cookie: 'kontur_session=' + oldToken }, body: JSON.stringify({ userId: 'anna' }) });
    const denied = await fetch(h.url + '/api/v1/bootstrap', { headers: { Authorization: 'Bearer ' + oldToken } });
    assert.equal(denied.status, 401);
});
